        f"Ниша: {user.niche or 'не указано'}\\n"
        f"Целевая аудитория: {user.audience or 'не указано'}\\n"
        f"Монетизация/продукт: {user.product or 'не указано'}\\n\\n"
        "Включи разделы (обязательно и в этом порядке):\\n"
        "1) Глубокий анализ ниши\\n"
        "2) Детальное позиционирование\\n"
        "3) Контент-план 30 дней (по дням)\\n"
        "4) 10 полностью написанных постов\\n"
        "5) Стратегию монетизации\\n"
        "6) Стратегию роста\\n"
