from database.models import User


def build_free_prompt(user: User) -> str:
    return (
        "Ты опытный launch-стратег и бренд-архитектор. "
        "Сформируй краткую стартовую стратегию на русском языке.\\n\\n"
        f"Данные пользователя:\\n"
        f"Идея: {user.idea or 'не указано'}\\n"
        f"Ниша: {user.niche or 'не указано'}\\n"
        f"Целевая аудитория: {user.audience or 'не указано'}\\n"
        f"Монетизация/продукт: {user.product or 'не указано'}\\n\\n"
        "Верни результат в четкой структуре:\\n"
        "1) Название проекта\\n"
        "2) Позиционирование\\n"
        "3) УТП\\n"
        "4) 3 идеи контента\\n"
        "5) 5 шагов запуска"
    )


